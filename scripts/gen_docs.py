"""Writes the generated README sections, or with --check fails if they are out of date."""

from __future__ import annotations

import re
import sys
from pathlib import Path

from fastapi.routing import APIRoute
from pydantic_core import PydanticUndefined

from wiredbench.api import ROUTERS
from wiredbench.config import Settings
from wiredbench.engine import box_facts, coverage
from wiredbench.services.exchange import OPTION_FIELDS

README = Path(__file__).parents[1] / "README.md"
COVERAGE = Path(__file__).parents[1] / "docs/box-coverage.md"
FIELDS = Path(__file__).parents[1] / "docs/box-fields.md"
EVIDENCE = {
    "unknown": "No evidence yet",
    "from_reference": "Reference only",
    "real_preset": "Seen in a real preset",
    "real_dump": "Seen in a real room dump",
    "real_room": "Checked in a real room",
}


def fields_doc() -> str:
    data = box_facts.load()
    capture = data["capture"]
    lines = [
        "# WIRED box fields",
        "",
        "Generated by `scripts/gen_docs.py` from `box_facts.json`. Do not edit by hand.",
        "",
        f"Read from unedited boxes in a real room on {capture['date']}, build `{capture['build']}`. Numbers are defaults",
        "in the order the server sends them. Labels are not sent, so a position is only named once something supports",
        "it, and a named position is still unverified until a box is changed and read again.",
        "",
        f"No reply from: {', '.join(f'`{name}`' for name in data['no_reply'])}. The cause is unconfirmed.",
        "",
        "| Box | Section | Default numbers | Named positions | Unnamed positions |",
        "|---|---|---|---|---|",
    ]
    named_total = unnamed_total = 0
    rows = []
    for name, fact in data["boxes"].items():
        named = {position: field for field, position, _ in OPTION_FIELDS.get(name, [])}
        unnamed = [str(i) for i in range(len(fact["numbers"])) if i not in named]
        named_total += len([p for p in named if p < len(fact["numbers"])])
        unnamed_total += len(unnamed)
        labels = ", ".join(f"{p}: {field}" for p, field in sorted(named.items()))
        rows.append(
            f"| `{name}` | {fact['section']} | `{fact['numbers']}` | {labels} | {', '.join(unnamed)} |"
        )
    lines[10:10] = [f"Named positions: {named_total}. Unnamed positions: {unnamed_total}.", ""]
    return "\n".join(lines + rows) + "\n"


def coverage_doc() -> str:
    total = coverage.summary()
    data = coverage.load()
    lines = [
        "# WIRED box coverage",
        "",
        "Generated by `scripts/gen_docs.py` from `box_coverage.json`. Do not edit by hand.",
        "",
        "Habbo can change boxes at any time, so a check only holds for the date beside it. The reference is",
        f"read at commit `{data.get('reference_commit')}`, for facts only.",
        "",
        f"- Boxes: {total['total']}",
        *(f"- {label}: {total[name]}" for name, label in EVIDENCE.items()),
        f"- Have a form: {total['has_form']}",
        f"- Option numbers mapped: {total['options_mapped']}",
        "",
        "| Box | Evidence | Form | Options | Room check |",
        "|---|---|---|---|---|",
    ]
    for row in coverage.rows():
        lines.append(
            f"| `{row['classname']}` | {EVIDENCE[row['evidence']]} | {'Yes' if row['has_form'] else ''} "
            f"| {'Yes' if row['options_mapped'] else ''} | {row['room_checked_on'] or ''} |"
        )
    return "\n".join(lines) + "\n"


def env_table() -> str:
    rows = ["| Variable | Default | Purpose |", "|---|---|---|"]
    for name, field in Settings.model_fields.items():
        default = "" if field.default in (None, PydanticUndefined) else f"`{field.default}`"
        rows.append(f"| `WB_{name.upper()}` | {default} | {field.description} |")
    return "\n".join(rows)


def api_table() -> str:
    rows = ["| Method | Path | Access |", "|---|---|---|"]
    routes = [route for router in ROUTERS for route in router.routes if isinstance(route, APIRoute)]
    for route in sorted(routes, key=lambda r: (r.path, sorted(r.methods))):
        access = "Public" if getattr(route.endpoint, "__wb_public__", False) else "Admin"
        methods = ", ".join(sorted(route.methods - {"HEAD"}))
        rows.append(f"| {methods} | `{route.path}` | {access} |")
    return "\n".join(rows)


def render(text: str) -> str:
    for name, body in (("env", env_table()), ("api", api_table())):
        pattern = rf"(<!-- generated:{name} -->\n).*?(<!-- /generated:{name} -->)"
        text, count = re.subn(pattern, lambda m, b=body: f"{m.group(1)}{b}\n{m.group(2)}", text, flags=re.S)
        if count != 1:
            sys.exit(f"README.md needs one generated:{name} section.")
    return text


def main() -> None:
    current = README.read_text(encoding="utf-8")
    updated = render(current)
    docs = {COVERAGE: coverage_doc(), FIELDS: fields_doc()}
    if "--check" in sys.argv:
        stale = any(
            not path.exists() or path.read_text(encoding="utf-8") != text for path, text in docs.items()
        )
        if current != updated or stale:
            sys.exit("Generated docs are out of date. Run: uv run python scripts/gen_docs.py")
        return
    README.write_text(updated, encoding="utf-8", newline="\n")
    for path, text in docs.items():
        path.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
